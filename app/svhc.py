"""Substances of very high concern (SVHC): the REACH Candidate List published by ECHA.

data/svhc_candidate_list.json is generated by tools/extract_svhc_candidate_list.py from the Excel export of
https://echa.europa.eu/candidate-list-table. Components are linked to the substances through their SVHC list:
CAS numbers, abbreviations such as "DEHP", or English names.
"""

from __future__ import annotations

import json
import re
import sqlite3
from collections import Counter
from functools import lru_cache
from pathlib import Path

from . import db

CANDIDATE_LIST_URL = "https://echa.europa.eu/candidate-list-table"
DATA_PATH = Path(__file__).resolve().parent.parent / "data" / "svhc_candidate_list.json"


@lru_cache(maxsize=1)
def _data() -> dict:
    try:
        return json.loads(DATA_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"substances": []}


def available() -> bool:
    return bool(_data().get("substances"))


def substances() -> list[dict]:
    return _data().get("substances", [])


def _word(text: str) -> str:
    return r"(?<![\w-])" + re.escape(text) + r"(?![\w-])"


@lru_cache(maxsize=1)
def _patterns() -> list[tuple[dict, re.Pattern]]:
    """For each substance, one pattern finding it in a free text: CAS numbers, abbreviations, English name."""
    out = []
    for s in substances():
        parts = [_word(cas) for cas in s.get("cas", [])]
        parts += [_word(a) for a in s.get("aliases", [])]
        name = s.get("name", "")
        if len(name) >= 4:
            parts.append("(?i:" + _word(name) + ")")
        if parts:
            out.append((s, re.compile("|".join(parts))))
    return out


def match_text(text: str) -> list[dict]:
    """Candidate List substances mentioned in a free text (the SVHC list of a component)."""
    if not text:
        return []
    return [s for s, pattern in _patterns() if pattern.search(text)]


def info() -> dict:
    """Source and version of the Candidate List, and whether it is loaded."""
    d = _data()
    return {"source": d.get("source", ""), "version": d.get("version", ""), "url": d.get("url", CANDIDATE_LIST_URL),
            "available": available()}


def list_all(conn: sqlite3.Connection) -> dict:
    counts: Counter = Counter()
    with_svhc = unmatched = 0
    for r in conn.execute("SELECT svhc_list FROM components WHERE svhc_list != ''"):
        with_svhc += 1
        found = match_text(r["svhc_list"])
        counts.update(s["id"] for s in found)
        unmatched += not found
    return info() | {
        "substances": [s | {"components": counts.get(s["id"], 0)} for s in substances()],
        "components_with_svhc": with_svhc,
        "unmatched_components": unmatched,
    }


def get(conn: sqlite3.Connection, sid: str) -> dict | None:
    s = next((x for x in substances() if x["id"] == sid), None)
    if s is None:
        return None
    rows = conn.execute("SELECT * FROM components WHERE svhc_list != '' ORDER BY manufacturer, mpn").fetchall()
    comps = [db.row_to_dict(r) for r in rows if s in match_text(r["svhc_list"])]
    return info() | s | {"components": comps}
